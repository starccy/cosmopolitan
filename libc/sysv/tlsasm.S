//	define __get_tls() impl for each kind of assembly opcode
//	that -mno-tls-direct-seg-refs can generate. you must use
//	-mno-red-zone too. see tool/build/fixupobj.c which fixes
//	the object code generated by gcc to call these functions
//
//	on linux and the bsds the tib pointer is read from %fs:0x38.
//	on a cosmo thread %fs points at the tib itself, whose 0x38 is
//	tib_self2. on a thread the host libc created %fs points at the
//	host's thread control block, where 0x38 is a slot glibc never
//	uses; we keep our tib pointer there. a zero there (or in our
//	windows tls slot) means the thread has no tib yet, and it gets
//	one on the spot from __tls_adopt()

	.macro	define_tls_getter name:req reg64:req reg32:req section:req
	.section \section,"ax",@progbits
	.align	16
\name:	mov	__hostos(%rip),%\reg32
	test	$_HOSTWINDOWS|_HOSTXNU,%\reg32
	jnz	1f
	mov	%fs:0x38,%\reg64 // Linux, FreeBSD, OpenBSD, NetBSD
	test	%\reg64,%\reg64
	jz	3f
	ret
1:	test	$_HOSTWINDOWS,%\reg32
	jnz	2f
	mov	%gs:0x30,%\reg64 // XNU
	ret
2:	mov	__tls_index(%rip),%\reg32	// Windows
	mov	%gs:0x1480(,%\reg64,8),%\reg64	// Hooray!
	test	%\reg64,%\reg64
	jz	3f
	ret
	.ifc	\reg64,rax
3:	jmp	__tls_slow
	.else
3:	push	%rax
	call	__tls_slow
	mov	%rax,%\reg64
	pop	%rax
	ret
	.endif
	.endfn	\name,globl
	.endm

//	returns tib in %rax for a thread that doesn't have one yet,
//	preserving every other register, including the vector ones
	.privileged
	.align	16
__tls_slow:
	cmpb	$0,__tls_enabled(%rip)
	je	9f
	lea	__tls_adopt(%rip),%rax
	test	%rax,%rax
	jz	9f
	push	%rbp
	mov	%rsp,%rbp
	push	%rcx
	push	%rdx
	push	%rsi
	push	%rdi
	push	%r8
	push	%r9
	push	%r10
	push	%r11
	sub	$512,%rsp
	and	$-64,%rsp
	fxsave	(%rsp)
	call	__tls_adopt
	fxrstor	(%rsp)
	lea	-64(%rbp),%rsp
	pop	%r11
	pop	%r10
	pop	%r9
	pop	%r8
	pop	%rdi
	pop	%rsi
	pop	%rdx
	pop	%rcx
	pop	%rbp
	ret
9:	xor	%eax,%eax
	ret
	.endfn	__tls_slow
	.weak	__tls_adopt

	define_tls_getter __get_tls_rax rax eax  .privileged
	define_tls_getter __get_tls_rbx rbx ebx  .privileged.__get_tls_rbx
	define_tls_getter __get_tls_rcx rcx ecx  .privileged.__get_tls_rcx
	define_tls_getter __get_tls_rdx rdx edx  .privileged.__get_tls_rdx
	define_tls_getter __get_tls_rdi rdi edi  .privileged.__get_tls_rdi
	define_tls_getter __get_tls_rsi rsi esi  .privileged.__get_tls_rsi
	define_tls_getter __get_tls_rbp rbp ebp  .privileged.__get_tls_rbp
	define_tls_getter __get_tls_r8  r8  r8d  .privileged.__get_tls_r8
	define_tls_getter __get_tls_r9  r9  r9d  .privileged.__get_tls_r9
	define_tls_getter __get_tls_r10 r10 r10d .privileged.__get_tls_r10
	define_tls_getter __get_tls_r11 r11 r11d .privileged.__get_tls_r11
	define_tls_getter __get_tls_r12 r12 r12d .privileged.__get_tls_r12
	define_tls_getter __get_tls_r13 r13 r13d .privileged.__get_tls_r13
	define_tls_getter __get_tls_r14 r14 r14d .privileged.__get_tls_r14
	define_tls_getter __get_tls_r15 r15 r15d .privileged.__get_tls_r15

	.macro	define_tls_adder name:req reg64:req tmp64:req
	.section .privileged.\name,"ax",@progbits
	.align	16
\name:	push	%\tmp64
	call	__get_tls_\tmp64
	add	%\tmp64,%\reg64
	pop	%\tmp64
	ret
	.endfn	\name,globl
	.endm

	define_tls_adder __add_tls_rax rax rcx
	define_tls_adder __add_tls_rbx rbx rax
	define_tls_adder __add_tls_rcx rcx rax
	define_tls_adder __add_tls_rdx rdx rax
	define_tls_adder __add_tls_rdi rdi rax
	define_tls_adder __add_tls_rsi rsi rax
	define_tls_adder __add_tls_rbp rbp rax
	define_tls_adder __add_tls_r8  r8  rax
	define_tls_adder __add_tls_r9  r9  rax
	define_tls_adder __add_tls_r10 r10 rax
	define_tls_adder __add_tls_r11 r11 rax
	define_tls_adder __add_tls_r12 r12 rax
	define_tls_adder __add_tls_r13 r13 rax
	define_tls_adder __add_tls_r14 r14 rax
	define_tls_adder __add_tls_r15 r15 rax

