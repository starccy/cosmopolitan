//	on aarch64 the thread register belongs to the host. every read of
//	tpidr_el0 in compiler output becomes a call to __get_tls_xN (see
//	tool/build/tlscc.c), which returns what cosmo code expects there:
//	the address just past our tib, where x28 used to point.
//
//	on linux the tib address is the second word at tpidr_el0. that's
//	the unused half of glibc's tcb on a host thread, and the word we
//	put after our own tib on a cosmo thread. on xnu, where apple keeps
//	tpidr_el0 to itself, it's a tsd slot we got from libSystem. a zero
//	means the thread has no tib yet, and __tls_adopt() makes one.

	.macro	define_tls_getter n:req t:req
	.privileged
	.balign	16
	.globl	__get_tls_x\n
__get_tls_x\n:
	adrp	x\n,__hostos
	ldr	w\n,[x\n,#:lo12:__hostos]
	tbnz	w\n,#3,2f		// _HOSTXNU
	mrs	x\n,tpidr_el0
	ldr	x\n,[x\n,#8]
	cbz	x\n,3f
1:	add	x\n,x\n,#1024
	ret
2:	str	x\t,[sp,#-16]!
	adrp	x\t,__tls_slot_offset
	ldr	x\t,[x\t,#:lo12:__tls_slot_offset]
	mrs	x\n,tpidrro_el0
	and	x\n,x\n,#-8
	ldr	x\n,[x\n,x\t]
	ldr	x\t,[sp],#16
	cbnz	x\n,1b
	.if	\n == 0
3:	str	x30,[sp,#-16]!
	bl	__tls_slow
	ldr	x30,[sp],#16
	.else
3:	stp	x0,x30,[sp,#-16]!
	bl	__tls_slow
	mov	x\n,x0
	ldp	x0,x30,[sp],#16
	.endif
	ret
	.endm

