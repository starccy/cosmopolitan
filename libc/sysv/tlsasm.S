//	tsd slot offset where xnu threads keep their tib, set up by
//	libc/runtime/set_tls.c
	.bss
	.balign	8
	.globl	__tls_slot_offset
__tls_slot_offset:
	.quad	0
	.previous

//	returns the thread register itself, for the code that sets it up
	.privileged
	.balign	16
	.globl	__get_tls_raw
__get_tls_raw:
	mrs	x0,tpidr_el0
	ret

//	returns in x0 our thread pointer for a thread that has no tib yet,
//	preserving every other register, vector ones included, and flags
	.privileged
	.balign	16
__tls_slow:
	stp	x29,x30,[sp,#-16]!
	mov	x29,sp
	sub	sp,sp,#0x290
	stp	x1,x2,[sp,#0x00]
	stp	x3,x4,[sp,#0x10]
	stp	x5,x6,[sp,#0x20]
	stp	x7,x8,[sp,#0x30]
	stp	x9,x10,[sp,#0x40]
	stp	x11,x12,[sp,#0x50]
	stp	x13,x14,[sp,#0x60]
	stp	x15,x16,[sp,#0x70]
	str	x17,[sp,#0x80]
	mrs	x1,nzcv
	str	x1,[sp,#0x88]
	stp	q0,q1,[sp,#0x90]
	stp	q2,q3,[sp,#0xb0]
	stp	q4,q5,[sp,#0xd0]
	stp	q6,q7,[sp,#0xf0]
	stp	q8,q9,[sp,#0x110]
	stp	q10,q11,[sp,#0x130]
	stp	q12,q13,[sp,#0x150]
	stp	q14,q15,[sp,#0x170]
	stp	q16,q17,[sp,#0x190]
	stp	q18,q19,[sp,#0x1b0]
	stp	q20,q21,[sp,#0x1d0]
	stp	q22,q23,[sp,#0x1f0]
	stp	q24,q25,[sp,#0x210]
	stp	q26,q27,[sp,#0x230]
	stp	q28,q29,[sp,#0x250]
	stp	q30,q31,[sp,#0x270]
	adrp	x0,__tls_adopt
	add	x0,x0,#:lo12:__tls_adopt
	cbz	x0,1f
	bl	__tls_adopt
	cbz	x0,1f
	add	x0,x0,#1024
1:	ldp	q0,q1,[sp,#0x90]
	ldp	q2,q3,[sp,#0xb0]
	ldp	q4,q5,[sp,#0xd0]
	ldp	q6,q7,[sp,#0xf0]
	ldp	q8,q9,[sp,#0x110]
	ldp	q10,q11,[sp,#0x130]
	ldp	q12,q13,[sp,#0x150]
	ldp	q14,q15,[sp,#0x170]
	ldp	q16,q17,[sp,#0x190]
	ldp	q18,q19,[sp,#0x1b0]
	ldp	q20,q21,[sp,#0x1d0]
	ldp	q22,q23,[sp,#0x1f0]
	ldp	q24,q25,[sp,#0x210]
	ldp	q26,q27,[sp,#0x230]
	ldp	q28,q29,[sp,#0x250]
	ldp	q30,q31,[sp,#0x270]
	ldr	x1,[sp,#0x88]
	msr	nzcv,x1
	ldp	x1,x2,[sp,#0x00]
	ldp	x3,x4,[sp,#0x10]
	ldp	x5,x6,[sp,#0x20]
	ldp	x7,x8,[sp,#0x30]
	ldp	x9,x10,[sp,#0x40]
	ldp	x11,x12,[sp,#0x50]
	ldp	x13,x14,[sp,#0x60]
	ldp	x15,x16,[sp,#0x70]
	ldr	x17,[sp,#0x80]
	mov	sp,x29
	ldp	x29,x30,[sp],#16
	ret
	.weak	__tls_adopt

#endif /* __x86_64__ */
