#!/bin/sh
# Rebuilds helper.inc, the prebuilt cosmo_dlopen() helpers plus the
# source text other hosts compile at runtime. Run it from anywhere on
# an x86_64 glibc machine that has gcc, musl-gcc and
# aarch64-linux-gnu-gcc, then commit helper.inc.
#
# Every glibc symbol is pinned to the oldest version that has it, so a
# helper built against a new glibc still loads on an old one.
set -e
cd "$(dirname "$0")"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

CFLAGS="-Os -fPIC -fno-stack-protector -fno-plt -fvisibility=hidden
        -U_FORTIFY_SOURCE -D_FORTIFY_SOURCE=0 -fno-asynchronous-unwind-tables"
LDFLAGS="-pie -rdynamic -nostartfiles -Wl,-z,execstack -Wl,--hash-style=both
         -Wl,--no-as-needed -Wl,--build-id=none -s"

pin() {
  base=$1
  echo "#ifndef __ASSEMBLER__"
  # dlopen is left out, the helper defines its own and finds glibc's
  # with dlsym(RTLD_NEXT)
  for s in dlsym dlclose dlerror pthread_attr_init \
           pthread_attr_setstack pthread_attr_setstacksize \
           pthread_attr_setdetachstate pthread_attr_destroy \
           pthread_key_create pthread_setspecific pthread_getattr_np \
           pthread_attr_getstack pthread_self __errno_location fork \
           setlocale tzset fflush setvbuf stdout sigaddset \
           __libc_start_main getpagesize write strlen memcpy memset \
           __libc_malloc __libc_free; do
    echo "__asm__(\".symver $s,$s@$base\");"
  done
  echo "__asm__(\".symver __register_atfork,__register_atfork@$2\");"
  echo "#endif"
}

pin GLIBC_2.2.5 GLIBC_2.3.2 >"$TMP/pin-x86_64.h"
gcc $CFLAGS -fcf-protection=none -include "$TMP/pin-x86_64.h" $LDFLAGS \
    -o "$TMP/glibc-x86_64" helper.c start-x86_64.S \
    -l:libdl.so.2 -l:libpthread.so.0

pin GLIBC_2.17 GLIBC_2.17 >"$TMP/pin-aarch64.h"
aarch64-linux-gnu-gcc $CFLAGS -include "$TMP/pin-aarch64.h" $LDFLAGS \
    -o "$TMP/glibc-aarch64" helper.c start-aarch64.S \
    -l:libdl.so.2 -l:libpthread.so.0

musl-gcc -Os -fPIC -fno-stack-protector -fno-asynchronous-unwind-tables \
    -pie -Wl,-z,execstack -Wl,--build-id=none -s \
    -o "$TMP/musl-x86_64" helper.c

blob() {
  echo "static const unsigned char $1[] = {"
  od -An -v -tu1 "$2" | sed 's/  */,/g; s/^,//; s/$/,/'
  echo "};"
}

{
  echo "// generated by libc/dlopen/helper/build.sh, do not edit"
  echo "static const char kHelperSource[] ="
  sed 's/\\/\\\\/g; s/"/\\"/g; s/^/    "/; s/$/\\n"/' helper.c
  echo ";"
  echo "#ifdef __x86_64__"
  blob kHelperGlibc "$TMP/glibc-x86_64"
  blob kHelperMusl "$TMP/musl-x86_64"
  echo "#elif defined(__aarch64__)"
  blob kHelperGlibc "$TMP/glibc-aarch64"
  echo "#endif"
} >helper.inc
cp "$TMP"/glibc-x86_64 "$TMP"/musl-x86_64 "$TMP"/glibc-aarch64 /mtmp/hd/ 2>/dev/null || true
